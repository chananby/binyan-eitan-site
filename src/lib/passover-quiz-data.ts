export type QuizCategory =
  | 'haggadah'
  | 'halacha'
  | 'minhagim'
  | 'torah'
  | 'chazal'
  | 'zmanim'

export type Difficulty = 'easy' | 'medium' | 'hard'

export type AgeGroup = 'kids' | 'teens' | 'adults'

export type QuestionType =
  | 'multiple-choice'
  | 'true-false'
  | 'fill-blank'
  | 'ordering'
  | 'matching'
  | 'who-said'

// ── Base ──────────────────────────────────────────────────────────────
interface BaseQuestion {
  id: string
  category: QuizCategory
  difficulty: Difficulty
  ageGroup: AgeGroup
  type: QuestionType
}

// ── Multiple Choice ───────────────────────────────────────────────────
export interface MultipleChoiceQuestion extends BaseQuestion {
  type: 'multiple-choice'
  question: string
  options: [string, string, string, string]
  correctIndex: 0 | 1 | 2 | 3
  explanation: string
}

// ── True / False ──────────────────────────────────────────────────────
export interface TrueFalseQuestion extends BaseQuestion {
  type: 'true-false'
  statement: string
  isTrue: boolean
  explanation: string
}

// ── Fill in the Blank ─────────────────────────────────────────────────
export interface FillBlankQuestion extends BaseQuestion {
  type: 'fill-blank'
  /** Use ___ to mark the blank */
  questionWithBlank: string
  answer: string
  hint?: string
  explanation: string
}

// ── Ordering ──────────────────────────────────────────────────────────
export interface OrderingQuestion extends BaseQuestion {
  type: 'ordering'
  question: string
  /** Items listed in the CORRECT order — UI will shuffle them */
  items: string[]
  explanation: string
}

// ── Matching ──────────────────────────────────────────────────────────
export interface MatchingQuestion extends BaseQuestion {
  type: 'matching'
  question: string
  /** Pairs in correct order — right column will be shuffled in UI */
  pairs: Array<{ left: string; right: string }>
  explanation: string
}

// ── Who Said It ───────────────────────────────────────────────────────
export interface WhoSaidQuestion extends BaseQuestion {
  type: 'who-said'
  quote: string
  context?: string
  options: [string, string, string, string]
  correctIndex: 0 | 1 | 2 | 3
  explanation: string
}

// ── Union ─────────────────────────────────────────────────────────────
export type QuizQuestion =
  | MultipleChoiceQuestion
  | TrueFalseQuestion
  | FillBlankQuestion
  | OrderingQuestion
  | MatchingQuestion
  | WhoSaidQuestion

